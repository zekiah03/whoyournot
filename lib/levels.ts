export const LEVEL_RANGES: { level: Level; min: number; max: number }[] = [
  { level: 1, min: 0, max: 20 },
  { level: 2, min: 21, max: 40 },
  { level: 3, min: 41, max: 60 },
  { level: 4, min: 61, max: 80 },
  { level: 5, min: 81, max: 100 },
];

export function scoreToLevel(score: number): Level {
  if (score <= 20) return 1;
  if (score <= 40) return 2;
  if (score <= 60) return 3;
  if (score <= 80) return 4;
  return 5;
}

