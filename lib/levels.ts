/**
 * Level system for trait centrality.
 *
 * Five levels mapped from the 0..100 `normalized` score.
 *   Lv.1 — この軸は自分と関係ない    (0..20)
 *   Lv.2 — 揺らぐが、自分は残る       (21..40)
 *   Lv.3 — どちらでもありうる        (41..60)
 *   Lv.4 — 失うと自分が崩れる         (61..80)
 *   Lv.5 — これが自分そのもの         (81..100)
 *
 * The collapse threshold (from `computeThresholds`) is expressed on the
 * preservation scale (0=lost, 100=intact), so it maps through the same
 * boundaries but with a different natural-language label below.
 */

export type Level = 1 | 2 | 3 | 4 | 5;

